type protoField struct {
	Type   string
	Number int32
}

var messageNames = []string{"RaidBuffs", "PartyBuffs", "IndividualBuffs", "Debuffs"}

func TestRenderMatchesCommonProto(t *testing.T) {
	common, err := os.ReadFile("../../proto/common.proto")
	if err != nil {
		t.Fatalf("read common.proto: %v", err)
	}
	rendered := Render(buffmanifest.Manifest)

	var retypes []string
	for _, message := range messageNames {
		want := parseProtoMessage(t, common, message)
		got := parseProtoMessage(t, rendered, message)

		for field, wantField := range want {
			gotField, ok := got[field]
			if !ok {
				t.Errorf("%s.%s is in common.proto but not rendered", message, field)
				continue
			}
			if gotField.Number != wantField.Number {
				t.Errorf("%s.%s is number %d in common.proto and %d rendered", message, field, wantField.Number, gotField.Number)
			}
			switch {
			case gotField.Type == wantField.Type:
			case wantField.Type == "TristateEffect" && gotField.Type == "bool":
				retypes = append(retypes, fmt.Sprintf("%s.%s", message, field))
			default:
				t.Errorf("%s.%s is %s in common.proto and %s rendered", message, field, wantField.Type, gotField.Type)
			}
		}
		for field := range got {
			if _, ok := want[field]; !ok {
				t.Errorf("%s.%s is rendered but not in common.proto", message, field)
			}
		}
	}

	// The ghost-talent retypes are approved: their Improved talent is absent from the
	// live Trait tree, so the tristate has no source and the manifest carries a bool.
	sort.Strings(retypes)
	t.Logf("%d approved TristateEffect -> bool retypes:", len(retypes))
	for _, field := range retypes {
		t.Logf("  %s", field)
	}
}

func TestRenderNextIndex(t *testing.T) {
	rendered := string(Render(buffmanifest.Manifest))

	for _, message := range messageNames {
		fields := parseProtoMessage(t, []byte(rendered), message)
		var max int32
		for _, field := range fields {
			if field.Number > max {
				max = field.Number
			}
		}
		want := fmt.Sprintf("// Next index: %d\nmessage %s {\n", max+1, message)
		if !strings.Contains(rendered, want) {
			t.Errorf("%s is not preceded by %q", message, want)
		}
	}
}

func TestRenderHeader(t *testing.T) {
	rendered := string(Render(buffmanifest.Manifest))
	want := `// Code generated by tools/gen_buffs_proto from tools/database/buffmanifest. DO NOT EDIT.
syntax = "proto3";
package proto;
option go_package = "./proto";

import "common.proto";
`
	if !strings.HasPrefix(rendered, want) {
		t.Errorf("rendered header is\n%s\nwant\n%s", rendered[:len(want)], want)
	}
	for _, line := range strings.Split(rendered, "\n") {
		if strings.HasPrefix(line, " ") {
			t.Errorf("line %q is space-indented; common.proto uses tabs", line)
		}
	}
}

var protoFieldRE = regexp.MustCompile(`^\s*([A-Za-z][\w.]*)\s+([a-z][a-z0-9_]*)\s*=\s*(\d+)\s*;`)

func parseProtoMessage(t *testing.T, raw []byte, message string) map[string]protoField {
	t.Helper()

	fields := map[string]protoField{}
	inMessage := false
	for _, line := range strings.Split(string(raw), "\n") {
		if !inMessage {
			inMessage = strings.HasPrefix(strings.TrimSpace(line), "message "+message+" {")
			continue
		}
		if strings.HasPrefix(strings.TrimSpace(line), "}") {
			break
		}
		match := protoFieldRE.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		number, err := strconv.Atoi(match[3])
		if err != nil {
			t.Fatalf("field %s of %s: %v", match[2], message, err)
		}
		fields[match[2]] = protoField{Type: match[1], Number: int32(number)}
	}

	if len(fields) == 0 {
		t.Fatalf("no fields parsed for message %s", message)
	}
	return fields
}
