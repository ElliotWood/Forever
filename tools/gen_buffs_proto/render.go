package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/wowsims/forever/tools/database/buffmanifest"
)

type message struct {
	Name        string
	Scope       buffmanifest.BuffScope
	Description string
}

// messages is the emission order of the four buff messages.
var messages = []message{
	{Name: "RaidBuffs", Scope: buffmanifest.ScopeRaid, Description: "Buffs that affect the entire raid."},
	{Name: "PartyBuffs", Scope: buffmanifest.ScopeParty, Description: "Buffs that affect a single party."},
	{Name: "IndividualBuffs", Scope: buffmanifest.ScopeIndividual, Description: "These are usually individual actions taken by other Characters."},
	{Name: "Debuffs", Scope: buffmanifest.ScopeDebuff},
}

const header = `// Code generated by tools/gen_buffs_proto from tools/database/buffmanifest. DO NOT EDIT.
syntax = "proto3";
package proto;
option go_package = "./proto";

import "common.proto";
`

// protoTypeNames is the proto type each manifest type emits. TristateEffect and Drums
// are declared in common.proto, which this file imports.
var protoTypeNames = map[buffmanifest.BuffProtoType]string{
	buffmanifest.ProtoBool:      "bool",
	buffmanifest.ProtoTristate:  "TristateEffect",
	buffmanifest.ProtoInt32:     "int32",
	buffmanifest.ProtoDouble:    "double",
	buffmanifest.ProtoEnumDrums: "Drums",
}

// Render emits proto/buffs.proto for the given manifest rows. Field numbers come from
// the manifest, which owns them, and fields are written in ascending number order.
func Render(manifest []buffmanifest.BuffSpec) []byte {
	var b strings.Builder
	b.WriteString(header)

	for _, msg := range messages {
		b.WriteString("\n")
		if msg.Description != "" {
			fmt.Fprintf(&b, "// %s\n", msg.Description)
		}

		specs := scopeRows(manifest, msg.Scope)
		retired := buffmanifest.Retired[msg.Scope]

		// A retired number is never handed out again, so the next free one is past
		// the live fields and the reserved ones alike.
		next := int32(1)
		for _, spec := range specs {
			if spec.Number >= next {
				next = spec.Number + 1
			}
		}
		for _, number := range retired {
			if number >= next {
				next = number + 1
			}
		}
		fmt.Fprintf(&b, "// Next index: %d\n", next)

		fmt.Fprintf(&b, "message %s {\n", msg.Name)
		if len(retired) > 0 {
			fmt.Fprintf(&b, "\treserved %s;\n", joinNumbers(retired))
		}
		for _, spec := range specs {
			fmt.Fprintf(&b, "\t%s %s = %d;\n", protoType(spec), spec.Field, spec.Number)
		}
		b.WriteString("}\n")
	}

	return []byte(b.String())
}

func protoType(spec buffmanifest.BuffSpec) string {
	name, ok := protoTypeNames[spec.Proto]
	if !ok {
		panic(fmt.Sprintf("%s has no proto type for %s", spec.Field, spec.Proto))
	}
	return name
}

func joinNumbers(numbers []int32) string {
	parts := make([]string, len(numbers))
	for i, number := range numbers {
		parts[i] = strconv.Itoa(int(number))
	}
	return strings.Join(parts, ", ")
}

func scopeRows(manifest []buffmanifest.BuffSpec, scope buffmanifest.BuffScope) []buffmanifest.BuffSpec {
	var rows []buffmanifest.BuffSpec
	for _, spec := range manifest {
		if spec.Scope == scope {
			rows = append(rows, spec)
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Number < rows[j].Number })
	return rows
}
